def main():
    root = Path(__file__).resolve().parent
    cuisines = []
    total = 0
    for cid, (name, emoji, desc, dishes) in MENU.items():
        items = []
        for d in dishes:
            name_, price, spicy, tag, note = d
            it = {"name": name_, "price": price, "spicy": spicy}
            if tag:
                it["tag"] = tag
            if note:
                it["desc"] = note
            items.append(it)
        total += len(items)
        cuisines.append({"id": cid, "name": name, "emoji": emoji,
                         "desc": desc, "dishes": items})

    out = {
        "name": "基米餐馆",
        "slogan": "今天想吃点什么？",
        "updated": "2026-10-10",
        "cuisines": cuisines,
    }
    path = root / "menu.json"
    path.write_text(json.dumps(out, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"菜系 {len(cuisines)} 个，菜品 {total} 道  ->  {path}")
    print(f"文件 {path.stat().st_size/1024:.1f} KB")
    for c in cuisines:
        print(f"  {c['emoji']} {c['name']:<12} {len(c['dishes']):>3} 道")


if __name__ == "__main__":
    main()
